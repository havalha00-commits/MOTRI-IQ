class AppStrings {
  AppStrings._();

  static final Map<String, String> ar = Map.unmodifiable(<String, String>{
    for (final AppStringEntry e in appStringEntries) e.key: e.ar,
  });

  static final Map<String, String> ku = Map.unmodifiable(<String, String>{
    for (final AppStringEntry e in appStringEntries) e.key: e.ku,
  });

  static final Map<String, String> en = Map.unmodifiable(<String, String>{
    for (final AppStringEntry e in appStringEntries) e.key: e.en,
  });

  static const List<String> supported = <String>['ar', 'ku', 'en'];

  /// يعيد نص المفتاح باللغة المطلوبة.
  ///
  /// عند اختيار الكردية أو الإنجليزية **لا** يعود إلى العربية إذا نقص المفتاح:
  /// يُبلّغ بخطأ في وضع التصحيح حتى يلتقطه الاختبار فورًا، ويعيد المفتاح نفسه
  /// في وضع الإصدار بدل عرض نص لا يُنتمي للغة المختارة.
  static String t(String key, String languageCode) {
    if (languageCode == 'ku' || languageCode == 'en') {
      final Map<String, String> table = languageCode == 'ku' ? ku : en;
      final String? value = table[key];
      if (value != null) return value;
      assert(
        false,
        languageCode == 'ku'
            ? 'نص كردي ناقص: "$key" — لا يجوز الرجوع إلى العربية'
            : 'English text missing for "$key" — falling back to Arabic is '
                'not allowed',
      );
      return key;
    }
    return ar[key] ?? key;
  }
}
